export function getTooltip(data) {
  const content = document.createElement('div');
  content.innerHTML = `
  <div class="cytoscape-popper">
    <h3>${data.id}</h3>
      <div>
        <span>Label:</span> ${data.id} <br/>
        <span>Type:</span> ${data?.type ?? 'unknown'}<br/>
        <button onClick=onButtonClick>More</button>
      </div>
    </div>
  `;
  return content;
}